"""Generate pooja_states.cns (Pooja's original moves).

Usage (repo root):
    python3 -I tools/fighters/pooja/gen_states.py

Her moves throw many near-identical projectiles, so they are generated here.
Each projectile is built from a base parameter dict plus per-throw overrides,
so every parameter appears exactly once.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OFF = "70, -300"  # throwing hand, relative to her feet

BASE = [
    ("projhitanim", "1591"), ("projremanim", "1591"), ("projcancelanim", "1591"),
    ("projpriority", "1"), ("projsprpriority", "3"),
    ("attr", "S, SP"), ("animtype", "Light"), ("guardflag", "MA"), ("hitflag", "MAF"),
    ("pausetime", "0, 8"), ("sparkno", "-1"), ("hitsound", "5, 1"), ("guardsound", "6, 0"),
    ("ground.type", "High"), ("ground.slidetime", "8"), ("ground.hittime", "12"),
    ("ground.velocity", "-10"), ("air.velocity", "-8, -10"), ("air.juggle", "1"),
]


def proj(state, tag, trigger, pid, anim, off, vel, accel, damage, **over):
    params = [("projid", str(pid)), ("projanim", str(anim)), ("offset", off), ("velocity", vel),
              ("accel", accel), ("damage", damage)] + BASE
    keys = [k for k, _ in params]
    params = [(k, over.pop(k.replace(".", "_"), v)) for k, v in params]
    params += [(k.replace("_", "."), v) for k, v in over.items() if k.replace("_", ".") not in keys]
    body = "\n".join("%s = %s" % kv for kv in params)
    return "[State %d, %s]\ntype = Projectile\n%s\n%s\n\n" % (state, tag, trigger, body)


# Sound 1500,0 (sounds/1500_0.wav): Pooja's "Must eat!", for every move that throws dates.
MUST_EAT = "1500, 0"


def head(n, anim, poweradd, extra=""):
    """Start of a date-throwing state: says "Must eat!" as the throw begins."""
    return ("[Statedef %d]\ntype    = S\nmovetype= A\nphysics = S\njuggle  = 6\npoweradd= %d\n"
            "velset = 0,0\nanim = %d\nctrl = 0\nsprpriority = 2\n%s\n"
            "[State %d, Must Eat]\ntype = PlaySnd\ntrigger1 = Time = 1\nvalue = %s\n\n"
            % (n, poweradd, anim, extra, n, MUST_EAT))


def end(n):
    return ("[State %d, End]\ntype = ChangeState\ntrigger1 = AnimTime = 0\nvalue = 0\nctrl = 1\n\n"
            ";---------------------------------------------------------------------------\n" % n)


