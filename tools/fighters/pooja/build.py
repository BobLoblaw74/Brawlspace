"""Build Pooja into content/chars/pooja (see tools/fighters/assemble.py).

Usage (repo root):
    python3 -I tools/fighters/pooja/build.py [--frames]

  --frames   regenerate art/ from source.png first (~1 min). Without it the
             existing art/ is packed as-is, keeping hand-drawn replacements.

pooja_states.cns is generated by gen_states.py (many near-identical
projectile controllers); edit gen_states.py and rerun it.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from assemble import assemble, sub1  # noqa: E402

EXTRA_ENTRIES = """;---------------------------------------------------------------------------
;Date Rain - one volley at a time
[State -1, Date Rain]
type = ChangeState
value = 1600
triggerall = command = "QCB_a"
triggerall = NumProjID(1600) = 0
trigger1 = var(1) ;Use combo condition (above)

;---------------------------------------------------------------------------
;Haggle Counter - from neutral only
[State -1, Haggle Counter]
type = ChangeState
value = 1610
triggerall = command = "QCB_b"
trigger1 = statetype = S
trigger1 = ctrl

"""


def cmd_hook(cmd):
    cmd = sub1(r'\[Command\]\s*\nname = "FF_ab"',
               '[Command]\nname = "QCB_a"\ncommand = ~D, DB, B, a\n\n'
               '[Command]\nname = "QCB_b"\ncommand = ~D, DB, B, b\n\n'
               '[Command]\nname = "FF_ab"', cmd)
    cmd = sub1(r"(\[State -1, Triple Kung Fu Palm\]\s*\ntype = ChangeState\s*\nvalue = )3000", r"\g<1>3100", cmd)
    cmd = cmd.replace("[State -1, Triple Kung Fu Palm]", "[State -1, Bumper Harvest]")
    cmd = cmd.replace("trigger2 = stateno != [3000,3050)", "trigger2 = stateno != [3100,3150)")
    idx = cmd.index("[State -1, High Kung Fu Blocking High]")
    idx = cmd.rindex(";---", 0, idx)
    return cmd[:idx] + EXTRA_ENTRIES + cmd[idx:]


assemble(
    "pooja", "Pooja", HERE,
    projectile="Date Scatter",
    stats=[(r"(?m)^life = 1000", "life = 1020"),
           (r"(?m)^walk\.fwd  = 9\.6", "walk.fwd  = 9.0")],
    quotes=["Fresh dates, special price. For you, double damage.",
            "You want a discount? Win first.",
            "Sweet, sticky, and you never saw them coming.",
            "My stall, my rules. Next customer!",
            "Too many dates? There is no such thing.",
            "Go home, eat something. You look weak."],
    movelist="""<#f0f000>:Throws:</>
Market Toss								[_B/_F]_+^Y

<#f0f000>:Special Moves:</>
Date Scatter_EX							_QDF^P
Date Rain (overhead)					_QDB^A
Haggle Counter							_QDB^B
Rising Ladle_EX							_DSF^P
Apron Swat_EX							_QDB^P
Market Rush_EX							_QDF^K
Sandal Knee_EX							_F_F^K

<#f0f000>:Super Moves:</>
Bumper Harvest <#bebebe>(1000)</>		_QDF_QDF^P
Final Offer <#bebebe>(1000)</>			_QDB_QDB^P
""",
    argv=sys.argv,
    cmd_hook=cmd_hook,
)
