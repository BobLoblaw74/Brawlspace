"""Build Bibble Babble into content/chars/bibblebabble (see tools/fighters/assemble.py).

Usage (repo root):
    python3 -I tools/fighters/sylvia/build.py [--frames]

  --frames   regenerate art/ from source.png and the sheets first (~1 min). Without it the
             existing art/ is packed as-is.

bibblebabble_states.cns is generated by gen_states.py; edit that and rerun it.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from assemble import assemble, sub1  # noqa: E402

EXTRA_ENTRIES = """;---------------------------------------------------------------------------
;Squawk
[State -1, Squawk]
type = ChangeState
value = 1600
triggerall = command = "QCB_a"
trigger1 = var(1) ;Use combo condition (above)

;---------------------------------------------------------------------------
;Grocery Skid - one bag at a time
[State -1, Grocery Skid]
type = ChangeState
value = 1610
triggerall = command = "QCB_b"
triggerall = NumProjID(1610) = 0
trigger1 = var(1) ;Use combo condition (above)

"""


def cmd_hook(cmd):
    cmd = sub1(r'\[Command\]\s*\nname = "FF_ab"',
               '[Command]\nname = "QCB_a"\ncommand = ~D, DB, B, a\n\n'
               '[Command]\nname = "QCB_b"\ncommand = ~D, DB, B, b\n\n'
               '[Command]\nname = "FF_ab"', cmd)
    cmd = sub1(r"(\[State -1, Triple Kung Fu Palm\]\s*\ntype = ChangeState\s*\nvalue = )3000", r"\g<1>3100", cmd)
    cmd = cmd.replace("[State -1, Triple Kung Fu Palm]", "[State -1, Chicken Stampede]")
    cmd = cmd.replace("trigger2 = stateno != [3000,3050)", "trigger2 = stateno != [3100,3150)")
    idx = cmd.index("[State -1, High Kung Fu Blocking High]")
    idx = cmd.rindex(";---", 0, idx)
    return cmd[:idx] + EXTRA_ENTRIES + cmd[idx:]


assemble(
    "bibblebabble", "Bibble Babble", HERE,
    projectile="Rubber Chicken Toss",
    stats=[(r"(?m)^life = 1000", "life = 1080"),
           (r"(?m)^walk\.fwd  = 9\.6", "walk.fwd  = 8.6"),
           (r"(?m)^walk\.back = -8\.8", "walk.back = -7.8")],
    quotes=["Bwaaak! That's chicken for 'you lose'.",
            "Careful, the bag's got eggs in it. Had.",
            "I've been throwing chickens since before you were born.",
            "Squeeze once for yes, twice for knockout.",
            "Mind the groceries on your way down.",
            "Bibble babble, toil and trouble!"],
    movelist="""<#f0f000>:Throws:</>
Bag Over the Head						[_B/_F]_+^Y

<#f0f000>:Special Moves:</>
Rubber Chicken Toss_EX					_QDF^P
Squawk									_QDB^A
Grocery Skid (low)						_QDB^B
Belly Bounce Uppercut_EX				_DSF^P
Bag Swing_EX							_QDB^P
Shuffle Charge_EX						_QDF^K
Sneaker Knee_EX							_F_F^K

<#f0f000>:Super Moves:</>
Chicken Stampede <#bebebe>(1000)</>		_QDF_QDF^P
Last Orders <#bebebe>(1000)</>			_QDB_QDB^P
""",
    argv=sys.argv,
    cmd_hook=cmd_hook,
)
