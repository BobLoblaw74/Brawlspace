"""Build Sylvia into content/chars/sylvia (see tools/fighters/assemble.py).

Usage (repo root):
    python3 -I tools/fighters/sylvia/build.py [--frames]

  --frames   regenerate art/ from sheet.jpg first (~1 min). Without it the
             existing art/ is packed as-is.

sylvia_states.cns is generated by gen_states.py; edit that and rerun it.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from assemble import assemble, sub1  # noqa: E402

EXTRA_ENTRIES = """;---------------------------------------------------------------------------
;The Tower - one at a time
[State -1, The Tower]
type = ChangeState
value = 1600
triggerall = command = "QCB_a"
triggerall = NumProjID(1600) = 0
trigger1 = var(1) ;Use combo condition (above)

;---------------------------------------------------------------------------
;Wheel of Fortune - from neutral only
[State -1, Wheel of Fortune]
type = ChangeState
value = 1610
triggerall = command = "QCB_b"
trigger1 = statetype = S
trigger1 = ctrl

"""


def cmd_hook(cmd):
    cmd = sub1(r'\[Command\]\s*\nname = "FF_ab"',
               '[Command]\nname = "QCB_a"\ncommand = ~D, DB, B, a\n\n'
               '[Command]\nname = "QCB_b"\ncommand = ~D, DB, B, b\n\n'
               '[Command]\nname = "FF_ab"', cmd)
    cmd = sub1(r"(\[State -1, Triple Kung Fu Palm\]\s*\ntype = ChangeState\s*\nvalue = )3000", r"\g<1>3100", cmd)
    cmd = cmd.replace("[State -1, Triple Kung Fu Palm]", "[State -1, Major Arcana]")
    cmd = cmd.replace("trigger2 = stateno != [3000,3050)", "trigger2 = stateno != [3100,3150)")
    idx = cmd.index("[State -1, High Kung Fu Blocking High]")
    idx = cmd.rindex(";---", 0, idx)
    return cmd[:idx] + EXTRA_ENTRIES + cmd[idx:]


assemble(
    "sylvia", "Sylvia", HERE,
    projectile="Tarot Throw",
    stats=[(r"(?m)^life = 1000", "life = 950"),
           (r"(?m)^walk\.fwd  = 9\.6", "walk.fwd  = 9.0"),
           (r"(?m)^walk\.back = -8\.8", "walk.back = -8.4")],
    quotes=["I saw this coming. I always see it coming.",
            "The cards never lie, dear. You do.",
            "Your future? Lying down, mostly.",
            "Shuffle, deal, done.",
            "Cross my palm with silver next time.",
            "The Tower fell. So did you."],
    movelist="""<#f0f000>:Throws:</>
Palm Reading							[_B/_F]_+^Y

<#f0f000>:Special Moves:</>
Tarot Throw_EX							_QDF^P
The Tower (overhead)					_QDB^A
Wheel of Fortune						_QDB^B
Crystal Uppercut_EX						_DSF^P
Shawl Swat_EX							_QDB^P
Seance Rush_EX							_QDF^K
Hem Kick_EX								_F_F^K

<#f0f000>:Super Moves:</>
Major Arcana <#bebebe>(1000)</>			_QDF_QDF^P
Final Reading <#bebebe>(1000)</>		_QDB_QDB^P
""",
    argv=sys.argv,
    cmd_hook=cmd_hook,
)
