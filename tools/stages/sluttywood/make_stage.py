"""Build the SluttyWood stage from source.jpg.

Usage (repo root):
    python3 -I tools/stages/sluttywood/make_stage.py

Writes content/stages/sluttywood.def and .sff. The illustration is scaled to
fill a 1280x720 screen with room for the camera to pan; fighters stand on the
asphalt just above the near rainbow crosswalk. A second layer adds a softly
pulsing additive glow, extracted from the bright saturated pixels (neon signs,
string lights, street lamps) of the source.
"""
import colorsys
import os
import subprocess
import sys

from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
SRC = os.path.join(HERE, "source.jpg")
STAGES = os.path.join(ROOT, "content", "stages")
ART = os.path.join(HERE, "art")

SCALE = 1.9          # 1024x434 source -> 1946x825
GROUND_SRC_Y = 375   # source row where the fighters' feet go (asphalt above the near crosswalk)
ZOFFSET = 610        # screen row of the ground line (720p)
SKYLINE_SRC_Y = 135  # glow only below this source row (neon signs, string lights, lamps)


def glow_layer(img):
    """Additive glow from bright, saturated pixels (neon, string lights, lamps)."""
    w, h = img.size
    px = img.load()
    out = Image.new("RGB", (w, h))
    opx = out.load()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            hh, s, v = colorsys.rgb_to_hsv(r / 255.0, g / 255.0, b / 255.0)
            # below the skyline (the sunset sky is bright too) and above the painted crosswalks
            if v > 0.82 and s > 0.45 and SKYLINE_SRC_Y < y < h * 0.75:
                opx[x, y] = (r, g, b)
    out = out.filter(ImageFilter.GaussianBlur(6))
    # boost: additive glow wants bright colour on black
    return out.point(lambda c: min(255, int(c * 1.7)))


def main():
    os.makedirs(ART, exist_ok=True)
    src = Image.open(SRC).convert("RGB")
    w, h = int(src.width * SCALE), int(src.height * SCALE)
    big = src.resize((w, h), Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=2, percent=60, threshold=2))
    big.save(os.path.join(ART, "0_0.png"), optimize=True)
    glow = glow_layer(src).resize((w, h), Image.LANCZOS)
    glow.save(os.path.join(ART, "1_0.png"), optimize=True)
    # stage-select thumbnail: 240x100 (sprite 9000,1), the whole scene
    thumb = src.resize((240, int(round(src.height * 240.0 / src.width))), Image.LANCZOS)
    off = (thumb.height - 100) // 2
    thumb.crop((0, off, 240, off + 100)).save(os.path.join(ART, "9000_1.png"), optimize=True)
    with open(os.path.join(ART, "axis.txt"), "w") as f:  # anchor = top-centre; thumbnail top-left
        f.write("0_0 %d 0\n1_0 %d 0\n9000_1 0 0\n" % (w // 2, w // 2))
    subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools", "png_to_sff.py"), ART,
                    os.path.join(STAGES, "sluttywood.sff")], check=True)

    top = ZOFFSET - int(round(GROUND_SRC_Y * SCALE))   # screen y of the image's top edge
    bound_x = w // 2 - 640 - 10                          # camera pan limit (keep the edges off screen)
    bound_high = max(0, -top - 10)                       # don't pan above the image
    with open(os.path.join(STAGES, "sluttywood.def"), "w") as f:
        f.write(DEF.format(top=top, bx=bound_x, bh=bound_high, z=ZOFFSET))
    print("stage written: content/stages/sluttywood.def (%dx%d, top at y=%d, pan +/-%d)" % (w, h, top, bound_x))


